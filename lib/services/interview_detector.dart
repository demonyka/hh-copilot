/// Эвристическое определение приглашения на собеседование по тексту сообщения.
/// Используется как запасной вариант, когда ИИ не настроен. Намеренно СТРОГОЕ:
/// обычная переписка/скрининг в чате — это не собеседование.
class InterviewDetector {
  const InterviewDetector._();

  // Сильные признаки реального шага к собеседованию: звонок, встреча, оффер.
  static const _positive = <String>[
    'собеседовани',
    'интервью',
    'созвон',
    'созвонимся',
    'созвониться',
    'позвони',
    'перезвон',
    'перезвоните',
    'наберите',
    'номер телефона',
    'ваш телефон',
    'на собеседование',
    'на встречу',
    'видеозвонок',
    'zoom',
    'google meet',
    'оффер',
    'предлагаем работу',
    'предлагаем вам работу',
    'готовы предложить работу',
    'выходите на работу',
    'когда удобно созвон',
    'во сколько удобно',
  ];

  // Явные признаки того, что это НЕ собеседование (авто/скрининг/отказ).
  static const _negative = <String>[
    'к сожалению',
    'отказ',
    'не подходит',
    'заполните анкету',
    'пройдите тест',
    'пройдите опрос',
    'спасибо за отклик',
    'ассистент',
    'на базе ai',
    'на базе ии',
    'бот',
    'в чате',
    'расскажите о себе',
    'готовы рассмотреть',
    'обсудим детали',
    'обсудить детали',
    'почему вам интересна',
    'мы получили ваш отклик',
    'ваш отклик просмотрен',
    'ваш отклик отклонён',
    'вакансия закрыта',
  ];

  static bool isInterview(String text) {
    final t = text.toLowerCase();
    for (final n in _negative) {
      if (t.contains(n)) return false;
    }
    for (final p in _positive) {
      if (t.contains(p)) return true;
    }
    return false;
  }
}
