/// Эвристическое определение приглашения на собеседование по тексту сообщения.
/// Используется как запасной вариант, когда ИИ не настроен.
class InterviewDetector {
  const InterviewDetector._();

  // Признаки приглашения: просьба созвониться/написать/встретиться и т.п.
  static const _positive = <String>[
    'собеседовани',
    'интервью',
    'созвон',
    'созвонимся',
    'созвониться',
    'позвон',
    'перезвон',
    'наберите',
    'наберу',
    'напишите мне',
    'ваш телефон',
    'номер телефона',
    'ваш номер',
    'когда удобно',
    'когда вам удобно',
    'когда сможете',
    'приходите',
    'встрет',
    'встреч',
    'пообщаться',
    'поговорить',
    'на связь',
    'свяжитесь',
    'свяжемся',
    'обсудить детали',
    'предлагаем',
    'готовы предложить',
    'оффер',
    'выходите',
    'ждём вас',
    'zoom',
    'google meet',
    'telegram для связи',
    'в телеграм',
    'ваша почта',
    'резюме заинтересовало',
  ];

  // Явные авто-фразы/отказы — не приглашение.
  static const _negative = <String>[
    'к сожалению',
    'отказ',
    'не подходит',
    'заполните анкету',
    'пройдите тест',
    'пройдите опрос',
    'спасибо за отклик',
    'ваш отклик отклонён',
    'ваш отклик просмотрен',
    'мы получили ваш отклик',
    'вакансия закрыта',
  ];

  static bool isInterview(String text) {
    final t = text.toLowerCase();
    for (final n in _negative) {
      if (t.contains(n)) return false;
    }
    for (final p in _positive) {
      if (t.contains(p)) return true;
    }
    return false;
  }
}
